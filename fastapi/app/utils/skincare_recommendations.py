def get_recommendations(skin_type: str, concerns: list = None) -> dict:
    """
    Тері типі мен мәселелерге сәйкес ұсыныстар қайтарады.
    skin_type: негізгі тері типі
    concerns: қосымша мәселелер тізімі
    """
    base = SKIN_TIPS.get(skin_type, SKIN_TIPS["normal"])
    result = {
        "skin_type": skin_type,
        "morning_routine": base["morning"],
        "evening_routine": base["evening"],
        "weekly_routine": base["weekly"],
        "key_ingredients": base["ingredients"],
        "avoid": base["avoid"],
        "combined_advice": None,
    }

    # Қосымша мәселелер бар болса
    if concerns:
        for concern in concerns:
            combo_key = tuple(sorted([skin_type, concern]))
            if combo_key in COMBINED_TIPS:
                result["combined_advice"] = COMBINED_TIPS[combo_key]
                break

    return result